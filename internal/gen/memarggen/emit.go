package memarggen

import (
	"fmt"
	"strings"
)

// Version is the extractor's version, stamped into the generated table's header.
//
// Condition 3 of 0007: the header answers "which authority, at which revision, read by which
// code" from inside the file. Bump it whenever a change here could change the table's
// *content*, so a reader finding a v1 table beside a v2 extractor knows the file is stale
// without running anything.
const Version = 1

// Output is where the emitted table is committed, relative to the repo root.
const Output = "internal/text/memarg.go"

// Emit renders the table as the generated Go source of package text.
//
// Deterministic — rows sorted by mnemonic, no map iteration — because the drift check compares
// generated text against the committed file, and a nondeterministic generator makes that
// comparison a coin flip rather than a control.
func (t *Table) Emit() (string, error) {
	byKind := map[string]int{}
	for _, r := range t.Rows {
		if r.Mnemonic == "" || r.Kind == "" {
			// Unreachable via Extract, which errors on both. Asserted anyway because Emit is
			// exported and a future caller could build a Table directly: an empty mnemonic
			// would render `"": 0` and read as a default for every instruction.
			return "", fmt.Errorf("row at lexer.mll:%d has an empty mnemonic or kind", r.Line)
		}
		byKind[r.Kind]++
	}

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by internal/gen/memarggen. DO NOT EDIT.
//
// Authority:  WebAssembly/spec interpreter/text/lexer.mll
// Revision:   %s
// Extractor:  memarggen v%d
// Rows:       %d
//
// The natural alignment each memory-accessing mnemonic defaults to when the text omits
// `+"`align=`"+`. Machine-derived per decision 0007's argument: the default is not in the text, so
// a wrong one produces an image that **decodes clean** and differs from the source only in a
// flags byte no assert_malformed inspects — invisible on the board by construction
// (contract §9 G-3).
//
// The values are log2 exponents, which is the form both authorities use: parser.mly:532's
// `+"`align`"+` production log2s the byte count the text writes, and encode.ml:221's `+"`memop`"+`
// writes the exponent straight into the flags field. So the number here is the number the
// flags byte holds.
//
// Regenerate with 'make memarg'; 'make memarg-drift' asserts this file still agrees with the
// pinned reference.

package text

// naturalAlign is the log2 alignment a memory-accessing mnemonic defaults to.
//
// A mnemonic **absent** from this map takes no memarg. That is load-bearing rather than
// incidental: `+"`immediates`"+`'s memarg arm looks the mnemonic up and a miss is a refusal, so a
// mnemonic dropped from this table becomes an unencodable instruction rather than one encoded
// with a zero alignment.
var naturalAlign = map[string]uint32{
`, t.SourceSHA, Version, len(t.Rows))

	for _, r := range t.Rows {
		// The key and its colon are padded as one unit, not the quoted key alone: padding
		// inside a `%q` puts the spaces *after* the closing quote and before the colon, which
		// gofmt rejects as a missing comma. Found by running the generator, which is the only
		// way — the string is well-formed Go text right up to the point where it is not.
		fmt.Fprintf(&b, "\t%-24s %d, // %-14s lexer.mll:%d\n",
			fmt.Sprintf("%q:", r.Mnemonic), r.Align, r.Kind, r.Line)
	}
	b.WriteString("}\n")
	return b.String(), nil
}
