package memarggen

import (
	"fmt"
	"strings"
)

// Version is the extractor's version, stamped into the generated table's header.
//
// Condition 3 of 0007: the header answers "which authority, at which revision, read by which
// code" from inside the file. Bump it whenever a change here could change the table's
// *content*, so a reader finding a v1 table beside a v2 extractor knows the file is stale
// without running anything.
const Version = 2

// Output is where the emitted table is committed, relative to the repo root.
const Output = "internal/text/memarg.go"

// Emit renders the table as the generated Go source of package text.
//
// Deterministic — rows sorted by mnemonic, no map iteration — because the drift check compares
// generated text against the committed file, and a nondeterministic generator makes that
// comparison a coin flip rather than a control.
func (t *Table) Emit() (string, error) {
	byKind := map[string]int{}
	for _, r := range t.Rows {
		if r.Mnemonic == "" || r.Kind == "" {
			// Unreachable via Extract, which errors on both. Asserted anyway because Emit is
			// exported and a future caller could build a Table directly: an empty mnemonic
			// would render `"": 0` and read as a default for every instruction.
			return "", fmt.Errorf("row at line %d has an empty mnemonic or kind", r.Line)
		}
		if r.From == "" {
			// **Both halves, or the citation is half a citation** — grave #529, and the same hard
			// error opgen's and opcodegen's Emit raise. A row with a Line and no file renders
			// `:266`, or worse gets a default file name that resolves against whichever pin's
			// lexer.mll the reader happens to open.
			return "", fmt.Errorf("row %q cites line %d of no file: two pins put two files named "+
				"lexer.mll in the tree with unrelated numberings (grave #529)", r.Mnemonic, r.Line)
		}
		byKind[r.Kind]++
	}

	if len(t.Sources) == 0 {
		// Unreachable via ExtractFrom, which populates it and refuses an empty authority list.
		// Asserted because Emit is exported: a sourceless header prints a table claiming no
		// authority at all, which is the one property 0007's condition 3 makes impossible.
		return "", fmt.Errorf("table has no sources; the header would claim no authority")
	}
	var auth strings.Builder
	for _, s := range t.Sources {
		fmt.Fprintf(&auth, "// Authority:  %s\n", s.LexerPath)
		fmt.Fprintf(&auth, "//             at %s", s.SHA)
		if s.Scope != "" {
			fmt.Fprintf(&auth, " — %s", s.Scope)
		}
		auth.WriteString("\n")
		// Per kind, not just a total: MEMORY_ATOMIC_NOTIFY is one row of 111, so this line is the
		// only channel in which that kind going to zero is a diff. See memarggen.Source.
		parts := make([]string, 0, len(s.ByKind))
		for _, k := range s.Kinds() {
			parts = append(parts, fmt.Sprintf("%s %d", k, s.ByKind[k]))
		}
		fmt.Fprintf(&auth, "//             %d rows (%s)\n", s.Total, strings.Join(parts, ", "))
	}

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by internal/gen/memarggen. DO NOT EDIT.
//
%s// Extractor:  memarggen v%d
// Rows:       %d
//
// The natural alignment each memory-accessing mnemonic defaults to when the text omits
// `+"`align=`"+`. Machine-derived per decision 0007's argument: the default is not in the text, so
// a wrong one produces an image that **decodes clean** and differs from the source only in a
// flags byte no assert_malformed inspects — invisible on the board by construction
// (contract §9 G-3).
//
// The values are log2 exponents, which is the form both authorities use: parser.mly:532's
// `+"`align`"+` production log2s the byte count the text writes, and encode.ml:221's `+"`memop`"+`
// writes the exponent straight into the flags field. So the number here is the number the
// flags byte holds.
//
// **More than one authority, because the grammar is the union of the tracked set** (§9 G-2), and
// the composition is base-wins for keywordgen's measured reason: the pins do not share a
// baseline, so a wholesale read of a proposal pin deletes core rows rather than adding its own.
// Each row's citation therefore names its *file* and not just a line — two pins put two files
// named lexer.mll in the tree, and a bare "lexer.mll:266" resolves against whichever one the
// reader opens (grave #529). For the atomic rows the default is also the only *legal* alignment,
// every atomic access being naturally aligned by the proposal's own validation rule, so a wrong
// row there is a rejected module rather than a slow one.
//
// Regenerate with 'make memarg'; 'make memarg-drift' asserts this file still agrees with every
// pinned reference above.

package text

// naturalAlign is the log2 alignment a memory-accessing mnemonic defaults to.
//
// A mnemonic **absent** from this map takes no memarg. That is load-bearing rather than
// incidental: `+"`immediates`"+`'s memarg arm looks the mnemonic up and a miss is a refusal, so a
// mnemonic dropped from this table becomes an unencodable instruction rather than one encoded
// with a zero alignment.
var naturalAlign = map[string]uint32{
`, auth.String(), Version, len(t.Rows))

	for _, r := range t.Rows {
		// The key and its colon are padded as one unit, not the quoted key alone: padding
		// inside a `%q` puts the spaces *after* the closing quote and before the colon, which
		// gofmt rejects as a missing comma. Found by running the generator, which is the only
		// way — the string is well-formed Go text right up to the point where it is not.
		fmt.Fprintf(&b, "\t%-26s %d, // %-20s %s:%d\n",
			fmt.Sprintf("%q:", r.Mnemonic), r.Align, r.Kind, r.From, r.Line)
	}
	b.WriteString("}\n")
	return b.String(), nil
}
