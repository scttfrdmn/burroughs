package keywordgen

import (
	"fmt"
	"strings"
)

// Version is the extractor's version, stamped into the generated table's header.
//
// Condition 3 of 0007, in this grammar: the header answers "which authority, at which
// revision, read by which code" from inside the file. Bump it whenever a change to this
// package could change the table's *content* — the header is then a claim about the pair,
// and a reader who finds a table stamped v1 next to a v2 extractor knows the file is
// stale without running anything.
const Version = 1

// Output is where the emitted table is committed, relative to the repo root. See
// opcodegen.Output for why it lives beside the emitter rather than at each caller.
const Output = "internal/text/keywords.go"

// Emit renders the table as the generated Go source of package text.
//
// The output is deterministic — arms sorted by keyword, no map iteration anywhere —
// because the drift check compares generated text against the committed file, and a
// nondeterministic generator would make that comparison a coin flip rather than a control.
func (t *Table) Emit() (string, error) {
	kinds := map[Kind]bool{}
	for _, a := range t.Arms {
		if a.Kind == "" {
			// Unreachable via Extract, which errors on an unread constructor. Asserted
			// anyway because Emit is exported and a future caller could construct a
			// Table directly: an empty kind would render `"nop": {}` and read as a
			// keyword that lexes to nothing.
			return "", fmt.Errorf("keyword %q has no token kind (lexer.mll:%d)", a.Keyword, a.Line)
		}
		kinds[a.Kind] = true
	}

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by internal/gen/keywordgen. DO NOT EDIT.
//
// Authority:  WebAssembly/spec interpreter/text/lexer.mll
// Revision:   %s
// Extractor:  keywordgen v%d
// Keywords:   %d
// Kinds:      %d
//
// This table is machine-derived from the reference interpreter's text lexer, per the
// argument of decision 0007 applied to the wat grammar: no spec-suite vector asserts
// that a valid mnemonic *lexes*, so a keyword this table wrongly omits is invisible on
// the board as a table defect (contract §9 G-3) and surfaces downstream as
// "unknown operator" on a module the spec calls well-formed. The accept direction needs
// the objective's other representation, and this is it.
//
// Regenerate with 'make keywords'; 'make keyword-drift' asserts this file still agrees
// with the pinned reference.

package text

// keywordKind is the parser token a keyword lexes to, in the reference's vocabulary
// rather than ours: the table is a transcription of an authority, so it speaks the
// authority's language and the mapping to this package's tokens happens at the point of
// use.
//
// A string rather than an enum because the vocabulary's authority is lexer.mll, and an
// enum here would be a second declaration of the same set — the thing this file exists to
// avoid.
type keywordKind string

// keywords is the wat keyword table: every literal the reference's keyword block
// recognizes, and the token it produces.
//
// A keyword *absent* from this map is not a token. That is the whole reject-direction
// contract, and the reference states it in one line — the keyword block's fallthrough,
// %s — which is why the eleven obsolete mnemonics (get_local, i32.wrap/i64, …)
// need no entries anywhere: they are absent, and absence is the rule.
var keywords = map[string]keywordKind{
`, t.SourceSHA, Version, len(t.Arms), len(kinds),
		fmt.Sprintf("`| _ -> unknown lexbuf` (lexer.mll:%d)", t.fallthroughLine))

	for _, a := range t.Arms {
		fmt.Fprintf(&b, "\t%q: %q, // lexer.mll:%d\n", a.Keyword, a.Kind, a.Line)
	}
	b.WriteString("}\n")
	return b.String(), nil
}
