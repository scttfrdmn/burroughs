package opcodegen

import (
	"fmt"
	"strings"
)

// Version is the extractor's version, stamped into the generated table's header.
//
// Condition 3 of 0007: the header answers "which authority, at which revision, read by
// which code" from inside the file. Bump it whenever a change to this package could
// change the table's *content* — the header is then a claim about the pair, and a
// reader who finds a table stamped v1 next to a v2 extractor knows the file is stale
// without running anything.
const Version = 2

// Output is where the emitted table is committed, relative to the repo root.
//
// Declared here, beside the emitter, so `make opcodes` and the drift check name one fact
// once. Previously both spelled it — the Makefile from the root, the test from its own
// directory with a `..` prefix — and promoting this package to internal/gen/ falsified the
// test's copy while the Makefile's stayed right. Two places knowing one fact (0006), where
// the fact is a location and the mover is a directory rename.
const Output = "internal/binary/optable.go"

// Emit renders the table as the generated Go source of package binary.
//
// The output is deterministic — arms sorted by (Prefix, Code), no map iteration
// anywhere — because the drift check compares generated text against the committed
// file, and a nondeterministic generator would make that comparison a coin flip
// rather than a control.
func (t *Table) Emit() (string, error) {
	var b strings.Builder
	// The generation header (0007, condition 3). Stamped, not deduced.
	fmt.Fprintf(&b, `// Code generated by internal/gen/opcodegen. DO NOT EDIT.
//
// Authority:  WebAssembly/spec interpreter/binary/decode.ml
// Revision:   %s
// Extractor:  opcodegen v%d
// Arms:       %d
//
// This table is machine-derived from the reference interpreter, per decision 0007:
// every spec-suite vector bearing on it is assert_malformed, so a table that wrongly
// *rejects* a valid opcode is invisible on the board by construction (contract §9
// G-3). The accept direction needs the objective's other representation, and this is
// it. Regenerate with 'make opcodes'; 'make opcode-drift' asserts this file still
// agrees with the pinned reference.

package binary

// opInfo is one opcode's immediate shape, as the reference interpreter reads it.
type opInfo struct {
	// mnemonic is the reference's own constructor name, and it is **load-bearing as of
	// decision 0014**: it is the join key the wat mnemonic→opcode table is generated
	// from, so a rename here moves an opcode. This comment read "a label, not a fact"
	// until that decision made it one.
	mnemonic string
	// imms is the immediate sequence in reading order. Order is load-bearing: a wrong
	// order shifts every subsequent byte.
	imms []imm
	// illegal marks an opcode the reference explicitly rejects. Present in the table
	// rather than absent from it — "rejected by the authority" and "unknown to the
	// table" are different facts, and conflating them is how a hole becomes an accept.
	illegal bool
	// escape marks a prefix byte (0xfb, 0xfc, 0xfd) whose operand is a u32 sub-opcode
	// read from the matching sub-table, rather than an instruction in its own right.
	// A third flavour of the distinction illegal draws: escape, illegal, and absent
	// are three different verdicts, and a decoder that cannot tell them apart reports
	// "no such opcode" for a whole proposal.
	escape bool
	// reason is the reference's own error text where the arm reports one
	// (misplaced ELSE/END), and is empty otherwise.
	reason string
	// refLine is the 1-indexed decode.ml line this row was read from, so any row can be
	// audited against the authority without a search.
	refLine int
}

// imm names one immediate reader, in the reference's vocabulary rather than ours: the
// table is a transcription of an authority, so it speaks the authority's language and
// the mapping to this package's readers happens at the point of use.
type imm string

const (
`, t.SourceSHA, Version, len(t.Arms))

	for _, c := range immConsts() {
		fmt.Fprintf(&b, "\t%s imm = %q\n", c.ident, c.imm)
	}
	b.WriteString(")\n")

	// One map per region. Separate maps rather than a composite key because the prefix
	// is read by a different reader (a byte) than the sub-opcode (a u32 LEB), and the
	// decoder dispatches on that difference.
	regions := []struct {
		prefix byte
		name   string
		doc    string
	}{
		{0x00, "opTable", "single-byte opcodes"},
		{0xfb, "opTableFB", "0xfb prefix (GC)"},
		{0xfc, "opTableFC", "0xfc prefix (misc: trunc_sat, bulk memory)"},
		{0xfd, "opTableFD", "0xfd prefix (SIMD)"},
	}
	for _, r := range regions {
		fmt.Fprintf(&b, "\n// %s — %s.\nvar %s = map[uint32]opInfo{\n", r.name, r.doc, r.name)
		for _, a := range t.Arms {
			if a.Prefix != r.prefix {
				continue
			}
			fmt.Fprintf(&b, "\t%#02x: {", a.Code)
			var fields []string
			if a.Mnemonic != "" {
				fields = append(fields, fmt.Sprintf("mnemonic: %q", a.Mnemonic))
			}
			if len(a.Imms) > 0 {
				idents := make([]string, len(a.Imms))
				for i, im := range a.Imms {
					idents[i] = identOf(im)
					if idents[i] == "" {
						// An immediate with no generated identifier would otherwise emit
						// `imms: []imm{}` — a *narrower* shape than the authority's,
						// silently. Erroring is the same choice as errUnrecognized: a
						// vocabulary gap is a build failure, never a quiet omission.
						return "", fmt.Errorf("no generated identifier for immediate %q (arm prefix=%#02x code=%#x, decode.ml:%d): add it to vocab",
							im, a.Prefix, a.Code, a.Line)
					}
				}
				fields = append(fields, fmt.Sprintf("imms: []imm{%s}", strings.Join(idents, ", ")))
			}
			if a.Illegal {
				fields = append(fields, "illegal: true")
			}
			if a.Escape {
				fields = append(fields, "escape: true")
			}
			if a.Reason != "" {
				fields = append(fields, fmt.Sprintf("reason: %q", a.Reason))
			}
			fields = append(fields, fmt.Sprintf("refLine: %d", a.Line))
			fmt.Fprintf(&b, "%s},\n", strings.Join(fields, ", "))
		}
		b.WriteString("}\n")
	}
	return b.String(), nil
}
