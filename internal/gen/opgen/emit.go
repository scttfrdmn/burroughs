package opgen

import (
	"fmt"
	"strings"
)

// Version is the extractor's version, stamped into the generated table's header.
//
// Condition 3 of 0007 in this grammar: the header answers "which authorities, at which
// revision, read by which code" from inside the file. Bump it whenever a change here could
// change the table's *content*, so a reader finding a v1 table beside a v2 extractor knows
// the file is stale without running anything.
const Version = 2

// Output is where the emitted table is committed, relative to the repo root.
//
// `internal/text`, because the encoder is the consumer: this table answers "what byte does
// this mnemonic emit", which is a question only the text side asks. The opcode table it is
// half-derived from lives in `internal/binary` and stays there — the two are different facts
// pointing in different directions, and merging them would put the decoder's table and the
// encoder's map in one file with one drift check for two authorities.
const Output = "internal/text/opcodes.go"

// Emit renders the join as the generated Go source of package text.
//
// Deterministic — rows sorted by keyword, ambiguities by constructor, no map iteration —
// because the drift check compares generated text against the committed file, and a
// nondeterministic generator makes that comparison a coin flip instead of a control.
func (t *Table) Emit() (string, error) {
	if len(t.Rows) == 0 {
		// Unreachable via Extract, whose floors fire first. Asserted because Emit is
		// exported: an empty table would render an empty map and read as "no mnemonic
		// encodes to anything", which is the vacuity failure in its final form.
		return "", fmt.Errorf("refusing to emit an empty table: %d rows", len(t.Rows))
	}

	var nGrammar, nLexer int
	for _, r := range t.Rows {
		switch r.Origin {
		case FromGrammar:
			nGrammar++
		case FromLexer:
			nLexer++
		default:
			return "", fmt.Errorf("row %q has origin %q, which is neither authority", r.Keyword, r.Origin)
		}
		if r.From == "" {
			// **Both fields, or the citation is half a citation** — grave #529, and the same hard
			// error opcodegen's Emit raises for a pathless arm. A row with a Line and no From
			// renders `:266`, or worse gets a default file name that resolves against whichever
			// pin's file of that name the reader happens to open.
			return "", fmt.Errorf("row %q cites line %d of no file: Origin says which *kind* of "+
				"authority named the constructor, and two pins put two files of each kind in the "+
				"tree (grave #529)", r.Keyword, r.Line)
		}
	}

	if len(t.Sources) == 0 {
		// Unreachable via ExtractFrom, which populates it and refuses an empty authority list.
		// Asserted because Emit is exported: a sourceless header prints a table claiming no
		// authority at all, which is the one property 0007's condition 3 makes impossible.
		return "", fmt.Errorf("table has no sources; the header would claim no authority")
	}
	var auth strings.Builder
	for _, s := range t.Sources {
		fmt.Fprintf(&auth, "// Authority:  %s  (%d grammar rows)\n", s.ParserPath, s.Grammar)
		fmt.Fprintf(&auth, "//             %s  (%d lexer rows)\n", s.LexerPath, s.Lexer)
		fmt.Fprintf(&auth, "//             at %s", s.SHA)
		if s.Scope != "" {
			fmt.Fprintf(&auth, " — %s", s.Scope)
		}
		auth.WriteString("\n")
	}

	var b strings.Builder
	fmt.Fprintf(&b, `// Code generated by internal/gen/opgen. DO NOT EDIT.
//
%s// Via:         internal/binary/optable.go, on the reference's constructor names
// Extractor:   opgen v%d
// Rows:        %d (grammar %d, lexer %d)
// Ambiguous:   %d
//
// This table is a **join, not an extraction** (decision 0014). Neither authority states
// "i32.add is 0x6a": parser.mly and lexer.mll name the reference's *constructor*
// (i32_add), and optable.go — itself machine-derived from the same revision's decode.ml —
// says which byte that constructor decodes from. The link is the constructor name, so no
// third place declares an opcode and there is nothing here to drift from optable.go.
//
// It exists for the accept direction. Every spec vector bearing on the encoder is a module
// the suite expects to *work*, so a wrong row emits a different instruction than the text
// denotes, and that decodes clean and scores green (contract §9 G-3). Three defects found
// while building this were of exactly that shape and none was visible on the board.
//
// **More than one authority, because the grammar is the union of the tracked set** (§9 G-2),
// and the join composes base-wins for keywordgen's measured reason: the pins do not share a
// baseline, so a wholesale read of a proposal pin deletes core clauses rather than adding its
// own. Each row's citation therefore names its *file* and not just its kind of authority — two
// pins put two parser.mly files and two lexer.mll files in the tree, and a bare "lexer.mll:266"
// resolves against whichever one the reader opens (grave #529).
//
// Regenerate with 'make opcodes-text'; 'make opcodes-text-drift' asserts this file still
// agrees with every pinned reference above.

package text

// opEncoding is the byte sequence a mnemonic's opcode occupies.
type opEncoding struct {
	// prefix is 0 for a single-byte opcode, or the prefix byte (0xfb, 0xfc, 0xfd) that
	// precedes a u32 sub-opcode.
	prefix byte
	// code is the opcode, or the sub-opcode when prefix is non-zero.
	code uint32
	// constructor is the reference's own name for this instruction, and it is the row's
	// *evidence*: a reader auditing why this mnemonic gets this byte follows the name into
	// optable.go, which cites its own decode.ml line. Not decoration — it is the join key.
	constructor string
}

// mnemonicOpcodes maps a wat mnemonic to the opcode it encodes to.
//
// A mnemonic *absent* from this map has no encoding: it is a type keyword, a script
// keyword, a module-field head, or a mnemonic whose instruction the reference does not
// build. Absence is the rule, exactly as it is for the keyword table.
//
// Mnemonics in ambiguousOpcodes below are present here with their *first* encoding and must
// not be read from this map — see that variable.
var mnemonicOpcodes = map[string]opEncoding{
`, auth.String(), Version, len(t.Rows), nGrammar, nLexer, len(t.Ambiguous))

	for _, r := range t.Rows {
		fmt.Fprintf(&b, "\t%q: {prefix: %#02x, code: %#x, constructor: %q}, // %s\n",
			r.Keyword, r.Prefix, r.Code, r.Constructor, originCite(r))
	}
	b.WriteString("}\n\n")

	b.WriteString(`// ambiguousOpcodes are the mnemonics the reference encodes two ways, choosing on the
// *operand* rather than on the mnemonic — so a lookup in mnemonicOpcodes alone is wrong for
// exactly these, and silently: both spellings decode clean, so no vector reports the
// mistake (contract §9 G-3).
//
// Emitted rather than resolved here, because resolving them needs the operand, which only
// the parser has. A caller encoding one of these mnemonics reads this map and chooses.
var ambiguousOpcodes = map[string][]opEncoding{
`)
	for _, a := range t.Ambiguous {
		fmt.Fprintf(&b, "\t%q: {", a.Keyword)
		parts := make([]string, len(a.Codes))
		for i, c := range a.Codes {
			parts[i] = fmt.Sprintf("{prefix: %#02x, code: %#x, constructor: %q}", c.Prefix, c.Code, a.Constructor)
		}
		fmt.Fprintf(&b, "%s},\n", strings.Join(parts, ", "))
	}
	b.WriteString("}\n")

	return b.String(), nil
}

// originCite renders a row's provenance as a citation into the authority that named it.
//
// Every row carries one, for the reason the other two generated tables do: a row a reader
// cannot audit without a search is a row whose provenance needs archaeology, and *a
// generated artifact whose provenance needs git archaeology has hearsay for authority*
// (0007, condition 3).
//
// The file comes from the row, not from its Origin. `From` already carries the pin — see Row.From
// and the grave it cites — so this function no longer decides which file a grammar row is in; a
// row's two halves are its own and are printed together.
//
// # The operator rides the citation, not the emitted struct
//
// Where a row has one, it is printed here rather than added as a field of `opEncoding`, and the
// reason is what each channel is for. The struct is what the encoder *reads*, and the encoder has
// no use for the operator — it already holds the resolved prefix and code. The citation is what a
// reader *follows*, and without the operator the row's `constructor: "i32_atomic_rmw"` names six
// rows of optable.go with no way to tell which: a citation that resolves to a family instead of a
// row, which is grave #529's half-citation in its third spelling. So the audit trail carries the
// whole join key and the data carries the answer.
func originCite(r Row) string {
	op := ""
	if r.Operator != "" {
		op = ", operator " + r.Operator
	}
	switch r.Origin {
	case FromGrammar, FromLexer:
		return fmt.Sprintf("%s:%d (%s%s)", r.From, r.Line, r.Kind, op)
	default:
		// Unreachable: Emit rejects an unknown origin before reaching here. Rendered rather
		// than panicking, because a generator that panics inside a format string is harder
		// to diagnose than one that emits a visible marker.
		return fmt.Sprintf("unknown origin %q", r.Origin)
	}
}
